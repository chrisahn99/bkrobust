"""Stage 0: assemble the canonical numbers file and write the report from it.

Every number Stage 0 prints has to resolve to a key in
``results/stage0/numbers.json``, which this script builds from the summaries the
four measurement scripts wrote. ``STAGE0.md`` is then generated from that file
rather than typed, because the failure this project keeps hitting is four
documents quoting the same quantity with four different denominators.

    python experiments/stage0_ladder.py
    python experiments/stage0_claim_radius.py
    python experiments/stage0_calibration.py --reps 5
    python experiments/stage0_differential.py --per-network 3
    python experiments/stage0_report.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "stage0"

#: Stage 0 summaries live beside this file; the Phase B ones are one directory over.
SOURCES = {
    "ladder": "ladder_summary.json",
    "claim_radius": "claim_radius_summary.json",
    "calibration": "calibration_summary.json",
    "differential": "differential.json",
    "reproduce": "reproduce.json",
    "frame": "../frame/frame_summary.json",
    "witness": "../frame/witness_summary.json",
    "frame_status": "../frame/status_summary.json",
    "declared": "../frame/declared_summary.json",
    "lever0": "lever0_differential.json",
    "ledger": "../ledger/table4.json",
    "ledger_sweep": "../ledger/sweep_summary.json",
}


def load() -> dict:
    """Read whichever summaries exist, and say which do not."""
    data, missing = {}, []
    for key, name in SOURCES.items():
        path = (OUT / name).resolve()
        if path.exists():
            data[key] = json.loads(path.read_text())
        else:
            missing.append(name)
    data["_missing"] = missing
    return data


def fmt(value: object) -> str:
    """Render a number or a small structure for prose."""
    if isinstance(value, float):
        return f"{value:.4g}"
    if isinstance(value, dict):
        return ", ".join(f"{k} {v}" for k, v in value.items())
    return str(value)


def report(d: dict) -> str:
    """The Stage 0 write-up, every figure resolved from the canonical file."""
    lines: list[str] = []
    add = lines.append
    add("# Stage 0 — results")
    add("")
    add("Generated by `experiments/stage0_report.py` from `results/stage0/numbers.json`.")
    add("Do not edit by hand. Predictions and decision rules were written first, in")
    add("`PREREGISTRATION.md`; the environment is in `ENV.md`.")
    add("")
    if d["_missing"]:
        add(f"⚠️ Not yet run: {', '.join(d['_missing'])}.")
        add("")

    rep = d.get("reproduce")
    if rep:
        add("## The gate")
        add("")
        add(
            f"{rep['rows_checked']} committed rows recomputed through the real entry point across "
            f"{len(rep['by_dispatch_leg'])} dispatch legs in {rep['seconds']} s: "
            f"**{rep['disagreements']} disagreements**. Nothing below was run before this passed."
        )
        add("")

    lad = d.get("ladder")
    if lad:
        fr = lad["free_rule"]
        law = lad["law_on_measurable_rows"]
        und = lad["undefined_stratum"]
        add("## The free rule against the committed radius")
        add("")
        add(
            f"{lad['rows']} admissible rows over {lad['distinct_pairs']} distinct pairs, "
            f"{lad['pairs_admissible_at_all_three_coverages']} of them admissible at all three "
            "coverages. The rows are not pairs, and the funnel has to say which it counts."
        )
        add("")
        add("| | count |")
        add("|---|---|")
        add(f"| exact | {fr['exact']} |")
        add(f"| within one | {fr['within_one']} |")
        add(f"| over-certifies, the dangerous direction | **{fr['over_certifies']}** |")
        add(f"| under-certifies, the conservative direction | {fr['under_certifies']} |")
        under_und = fr["under_certifies_in_undefined_stratum"]
        add(f"| of those, in the undefined-separation stratum | {under_und} |")
        add("")
        add(
            f"The errors are one-sided. Over-certification happens on "
            f"{fmt(fr['over_certifies_by_network'])}. The undefined stratum holds "
            f"{und['rows']} rows with radii {fmt(und['radius_distribution'])}, and the rule has no "
            "information there at all."
        )
        add("")
        add(
            f"The law that transfers is `r >= min(s, k_g0)`: equality on {law['radius_equal_min']} "
            f"of {law['rows']} measurable rows, radius larger on {law['radius_greater_than_min']}, "
            f"smaller on {law['radius_less_than_min']}. The radius never exceeds `k_g0` "
            f"({law['radius_greater_than_k_g0_anywhere']} rows) and equals it on "
            f"{law['radius_equal_k_g0']}."
        )
        add("")
        icc = lad["icc_radius_is_one"]
        add(
            f"Intraclass correlation of the `r = 1` indicator: **{icc['icc']}** over "
            f"{icc['networks']} networks. The network is the unit; no per-row interval is printed."
        )
        add("")

    cr = d.get("claim_radius")
    if cr:
        add("## The unit")
        add("")
        one, total = cr["claim_radius_is_one"], cr["coverage_1_rows"]
        add(
            f"At coverage 1.0, **{one} of {total}** rows fail "
            f"under a single claim retraction and {cr['no_single_retraction_breaks_validity']} "
            "survive. That is not a discovery: the admissibility gate admits a pair only on that "
            "condition. It is the reason the committed radii cannot be read as a count of "
            "tolerable errors."
        )
        add("")
        hop_at_one = fmt(cr["hop_radius_where_claim_radius_is_one"])
        add(f"Hop radius where the claim radius is 1: {hop_at_one}.")
        add("")
        add(
            f"Median asserted claims {cr['median_asserted']}, median closure `k_g0` "
            f"{cr['median_k_g0']}. phi_1, the fraction of single retractions that invalidate, runs "
            f"{fmt(cr['phi_1']['min'])} to {fmt(cr['phi_1']['max'])} with median "
            f"{fmt(cr['phi_1']['median'])}: it varies where the claim radius does not."
        )
        add("")
        nest = cr["coverage_sweep_nesting"]
        viol = ", ".join(v["network"] for v in nest["violations"])
        add(
            f"The coverage sweep is not nested: `K(0.5)` is inside `K(1.0)` on "
            f"{nest['k05_in_k1']} of {nest['networks']} networks but `K(0.25)` is inside `K(0.5)` "
            f"on only {nest['k025_in_k05']}. It fails on {viol}."
        )
        add("")
        o = cr["o_g0_not_identified"]
        add(
            f"Of the {o['rows']} rows rejected as `o_g0_not_identified`, "
            f"{o.get('not_amenable', 0)} are non-amenable: the effect is not identifiable by "
            "adjustment there, so no definition of the optimal set recovers them."
        )
        add("")

    diff = d.get("differential")
    if diff:
        st, ne = diff["stride"], diff["nested"]
        add("## What the patches changed")
        add("")
        add(
            f"{st['checked']} committed rows recomputed under the patched path. "
            f"{st['mismatched']} differ, and every one of them is `k_g0` on a row that was "
            "rejected, where the committed value was a dataclass default of zero that had never "
            "been assigned. No admissible row moved on any field."
        )
        add("")
        add(
            f"The old rejection label decomposes as {fmt(st['label_decomposition'])}, measured "
            "through the pipeline rather than a separate diagnostic."
        )
        add("")
        add(
            f"Under the nested selection: {ne['coverage_1_mismatched']} of "
            f"{ne['coverage_1_checked']} coverage-1.0 rows differ, which is the differential test "
            "that lets the committed rows stand. At partial coverage "
            f"{ne['partial_coverage_changed']} of {ne['partial_coverage_checked']} rows change "
            f"status: {fmt(ne['status_delta'])}. Which claims the selection keeps decides whether "
            "the instance survives."
        )
        add("")

    cal = d.get("calibration")
    if cal:
        add("## The ladder, scored against the truth")
        add("")
        add(
            f"{cal['scored']} of {cal['draws']} draws scored over {cal['networks_scored']} "
            f"networks in {cal['seconds']} s. Status composition: {fmt(cal['status'])}."
        )
        add("")
        add(
            f"The committed set is invalid at the truth on **{cal['z_invalid_at_truth']}** rows "
            f"({fmt(cal['z_invalid_at_truth_by_rate'])} by corruption rate). That is the outcome "
            "the certificate exists for, and it is rare, which is why the miss rate alone has no "
            "power and the table reports detection and false alarm conditioned on the truth."
        )
        add("")
        add(f"Claim radius by corruption rate: {json.dumps(cal['r_claim_by_rate'])}.")
        add("")
        add(
            f"Identifiability radius: {fmt(cal['r_id_distribution'])}. Leverage "
            f"`r_hop / r_claim`: {fmt(cal['leverage'])}."
        )
        add("")
        inv = cal["invariants"]
        add(
            f"Invariants: rows with claim radius above hop radius **{inv['r_claim_gt_r_hop']}**, "
            f"rows with identifiability radius below claim radius **{inv['r_id_lt_r_claim']}**. "
            "Both must be zero; either one above zero halts the sweep."
        )
        add("")
        table = cal.get("ladder_corrupted_only") or cal.get("ladder_all_scored") or {}
        if table:
            add(
                "Corrupted rows only. Miss is the over-certification rate, detection is the share "
                "of truly invalid rows the instrument warned on, false alarm the share of valid "
                "rows it needlessly refused, moves the mean certified safe moves."
            )
            add("")
            add("| instrument | miss | 95% CI | detection | false alarm | moves |")
            add("|---|---|---|---|---|---|")
            for rung, v in table.items():
                ci = v["dangerous_ci"]
                add(
                    f"| `{rung}` | {v['dangerous_rate']} | [{ci[0]}, {ci[1]}] | "
                    f"{v['detection_rate']} | {v['false_alarm_rate']} | "
                    f"{v['mean_certified_moves']} |"
                )
            add("")

    fr = d.get("frame")
    if fr:
        t, fvc = fr["totals"], fr["frame_vs_committed"]
        add("## The frame, drawn from the estimated graph alone")
        add("")
        add(
            f"Treatments in or beside a chain component, outcomes among their possible "
            f"descendants, nothing else filtered: **{t['frame_pairs']} candidate pairs** over "
            f"{fr['networks_yielding_frame']} networks, against "
            f"{fvc['committed_admissible_pairs']} admissible pairs over "
            f"{fr['networks_yielding_committed_instances']} networks under the true-DAG gate. "
            f"An expansion of **{fvc['expansion_factor']}x**."
        )
        add("")
        add(
            f"Every one of the {fvc['committed_inside_frame']} committed pairs is inside the "
            f"frame and {fvc['committed_outside_frame']} fall outside it, so the frame strictly "
            "contains the population every previous result was measured on and no committed "
            "number is orphaned. The eight networks that yield a frame but yielded no committed "
            "instance are the ones the true-DAG gate removed entirely."
        )
        add("")
        add(
            f"The frozen sample is {t['sampled_pairs']} rows at a per-network cap of "
            f"{fr['cap']}, with the inclusion probability recorded per network; "
            f"{fr['capped_networks']} networks are capped."
        )
        add("")

    wit = d.get("witness")
    if wit:
        gap = wit["unit_gap_against_claim_depth"]
        add("## The first-failing retraction set")
        add("")
        add(
            f"On the {wit['rows']} committed rows at full coverage over {wit['networks']} "
            f"networks, the retraction depth is {fmt(wit['retraction_depth'])} and what it costs "
            f"is {fmt(wit['what_it_costs'])}. The single claim whose retraction invalidates the "
            "set also makes the query non-amenable, so there is no stratum here in which the "
            "committed set breaks and another valid set survives. Knowledge is buying "
            "identifiability, not a better set."
        )
        add("")
        add(
            f"The witness is unique on **{wit['sets_at_depth']['one_set_only']}** of "
            f"{wit['rows']} rows, with a median of {wit['sets_at_depth']['median']} and a "
            f"maximum of {wit['sets_at_depth']['max']} sets at that depth. The sentence an "
            "analyst reads is therefore well posed rather than one of many."
        )
        add("")
        add("No instrument ever reads below the claim depth, and each reads above it as its own")
        add("unit permits. The gap is the unit mismatch, not an error.")
        add("")
        add("| instrument | reads high | exact | reads low | widest gap |")
        add("|---|---|---|---|---|")
        for name in ("free_rule", "hop_radius", "closure_size"):
            v = gap[name]
            add(
                f"| `{name}` | {v['reads_high']} | {v['exact']} | {v['reads_low']} | "
                f"{v['max_gap']} |"
            )
        add("")
        sits = wit.get("where_the_retraction_sits")
        if sits:
            add(
                "Where the binding claim sits explains when the free rule is right. Over all "
                f"rows: {fmt(sits['all_rows'])}. Nearly two thirds touch the treatment and four "
                "rows touch the outcome, which is the locality this project measured for "
                "orientation statements, restated in the unit an analyst asserts."
            )
            add("")
            add(
                "Split by whether the free rule was exact: where it reads high the binding claim "
                f"is {fmt(sits['where_free_rule_reads_high'])}; where it is exact it is "
                f"{fmt(sits['where_free_rule_is_exact'])}. The hop distance from the treatment to "
                "the adjustment set predicts the retraction depth when the claim that binds is "
                "incident to the treatment, and overstates it when the binding claim lies "
                "elsewhere in the chain component. That is a characterisation of the free rule "
                "rather than a contest with it."
            )
            add("")

    dq = d.get("declared")
    if dq:
        add("## The queries the applied papers' own authors declared")
        add("")
        add(
            f"{dq['files_with_declared_roles']} files carry an exposure and an outcome their "
            f"authors marked, {dq['with_author_adjustment_set']} also name an adjustment set, "
            f"{dq['with_selection_node']} a selection node and {dq['with_latent_nodes']} latent "
            "nodes. Those annotations were captured by the parser and discarded, which is why the "
            "domain-documented stratum had no rows. They are now carried through, and the result "
            "runs the other way from every sampled pair in this project."
        )
        add("")
        add(
            f"Of the {dq['certifiable']} declared queries we can certify, "
            f"**{dq['certifiable_and_nothing_breaks']} are not broken by any retraction inside "
            f"the depth budget** and the upward search finds no failing graph at all. Exactly "
            f"{dq['certifiable_and_breaks_inside_budget']} breaks, and it is a four-node teaching "
            "file. Against that, every one of the 540 sampled rows at full coverage breaks at a "
            "single retraction."
        )
        add("")
        add(
            "The two populations are near complements, and the reason is mechanical. A pair is "
            "admitted only when some single retraction changes validity, so a query robust to "
            "every retraction is rejected before it is ever measured. The population every radius "
            "in this project was computed on is therefore close to the complement of the queries "
            "these papers were written to answer. That is a statement about applicability and it "
            "belongs in the funnel, not in a limitations paragraph."
        )
        add("")
        add("| network | exposure | outcome | status | claims | retraction depth |")
        add("|---|---|---|---|---|---|")
        for r in dq["rows"]:
            add(
                f"| `{r['network']}` | {r['exposure']} | {r['outcome']} | {r['status']} | "
                f"{r['n_claims']} | {r['r_claim']} |"
            )
        add("")

    st = d.get("frame_status")
    if st:
        add("## Status composition on the frozen frame")
        add("")
        add(
            f"{st['frame_rows_evaluated']} frame rows over {st['networks_evaluated']} networks, "
            f"{st['evaluations']} evaluations in {st['seconds']} s. Networks excluded for size: "
            f"{', '.join(e['network'] for e in st['excluded_for_size']) or 'none'}."
        )
        add("")
        add("| arm and coverage | rows | certifiable | composition |")
        add("|---|---|---|---|")
        for key, v in st["status_by_arm"].items():
            total = sum(v.values())
            ok = v.get("ok", 0)
            rest = ", ".join(f"{k} {n}" for k, n in sorted(v.items()) if k != "ok")
            add(f"| `{key}` | {total} | {ok} ({ok / total:.1%}) | {rest} |")
        add("")
        for key, v in st["radii_by_arm"].items():
            if v:
                add(
                    f"`{key}`: {v['rows']} certifiable rows over {v['networks']} networks, "
                    f"hop radius {fmt(v['r_hop'])}, claim radius {fmt(v['r_claim'])}, "
                    f"median closure {v['median_k_g0']}, mean wrong claims "
                    f"{v['mean_wrong_claims']}, invalid at the truth {v['z_invalid_at_truth']}."
                )
                add("")
    return "\n".join(lines) + "\n"


def main() -> None:
    """Build the canonical numbers file and the report."""
    data = load()
    (OUT / "numbers.json").write_text(json.dumps(data, indent=1))
    (OUT / "STAGE0.md").write_text(report(data))
    print(f"wrote {OUT / 'numbers.json'} and {OUT / 'STAGE0.md'}")
    if data["_missing"]:
        print("missing:", ", ".join(data["_missing"]))


if __name__ == "__main__":
    main()
